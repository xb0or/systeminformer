def main():
    roots = [
        r"F:\desktop\code\SystemInformer\plugins",
        r"F:\desktop\code\SystemInformer\SystemInformer",
    ]
    total = 0
    for root in roots:
        for dirpath, dirs, files in os.walk(root):
            for fn in files:
                if not fn.endswith((".c", ".cpp")):
                    continue
                p = os.path.join(dirpath, fn)
                with io.open(p, "r", encoding="utf-8-sig") as f:
                    text = f.read()
                n = 0
                for key in sorted(PATCH3, key=len, reverse=True):
                    src = 'L"' + key + '"'
                    if src in text:
                        n += text.count(src)
                        text = text.replace(src, 'L"' + PATCH3[key] + '"')
                if n:
                    has_cjk = any('\u4e00' <= c <= '\u9fff' for c in text)
                    with io.open(p, "w", encoding="utf-8-sig" if has_cjk else "utf-8", newline="") as f:
                        f.write(text)
                    total += n
                    print("%-45s %d" % (os.path.relpath(p, root), n))
    print("TOTAL:", total)


if __name__ == "__main__":
    main()
