def translate_rc(path):
    with io.open(path, "r", encoding="utf-8-sig") as f:
        text = f.read()

    replaced = []
    # 按键长度降序替换，避免子串问题（带完整引号本身已安全，双保险）
    for key in sorted(RC_MAP, key=len, reverse=True):
        quoted = '"' + key + '"'
        if quoted in text:
            cnt = text.count(quoted)
            text = text.replace(quoted, '"' + RC_MAP[key] + '"')
            replaced.append((key, cnt))

    # UTF-8 with BOM 写回（rc.exe 需要 BOM 识别 UTF-8）
    with io.open(path, "w", encoding="utf-8-sig", newline="") as f:
        f.write(text)

    return replaced


